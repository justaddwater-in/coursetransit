<?php
defined('ABSPATH') || exit;

(static function () use ($attributes) {

if (!function_exists('wc_get_product')) {
    return;
}

require_once dirname(__DIR__) . '/helpers.php';

$limit = isset($attributes['limit']) ? max(1, min(12, absint($attributes['limit']))) : 6;
$columns = isset($attributes['columns']) ? max(1, min(4, absint($attributes['columns']))) : 3;
$show_image = !isset($attributes['showImage']) || (bool) $attributes['showImage'];
$show_description = !isset($attributes['showDescription']) || (bool) $attributes['showDescription'];
$show_progress = !isset($attributes['showProgress']) || (bool) $attributes['showProgress'];
$sort = isset($attributes['sort']) ? sanitize_key((string) $attributes['sort']) : 'recent';
$button_text = isset($attributes['buttonText']) ? trim((string) $attributes['buttonText']) : __('Continue Course', 'coursetransit');
$button_text = $button_text !== '' ? $button_text : __('Continue Course', 'coursetransit');
$image_size = isset($attributes['imageSize']) ? sanitize_key((string) $attributes['imageSize']) : 'medium_large';
$image_size = in_array($image_size, ['thumbnail', 'medium', 'medium_large', 'large', 'full'], true) ? $image_size : 'medium_large';
$image_ratio = isset($attributes['imageRatio']) ? sanitize_key((string) $attributes['imageRatio']) : '16-9';
$image_ratio = in_array($image_ratio, ['16-9', '4-3', '1-1', 'auto'], true) ? $image_ratio : '16-9';

$wrapper = get_block_wrapper_attributes(['class' => 'coursetransit-block coursetransit-my-courses']);
// phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by get_block_wrapper_attributes(), which escapes attribute values.
echo '<div ' . $wrapper . '>';
$show_heading = !empty($attributes['showHeading']);

if (!is_user_logged_in()) {
    $login_url = function_exists('wc_get_page_permalink') ? wc_get_page_permalink('myaccount') : wp_login_url();
    echo '<div class="coursetransit-block-notice"><p>' . esc_html__('Please log in to view your courses.', 'coursetransit') . '</p>';
    echo '<a class="wp-element-button" href="' . esc_url($login_url) . '">' . esc_html__('Log In', 'coursetransit') . '</a></div></div>';
    return;
}

$enrollment_map = coursetransit_blocks_get_enrolled_product_data(get_current_user_id());
$product_ids = array_keys($enrollment_map);
$courses = coursetransit_blocks_get_course_products($product_ids, 50, $enrollment_map);

if ($show_heading) {
    $course_count = count($product_ids);
    echo '<div class="coursetransit-my-courses__header">';
    echo '<h2 class="wp-block-heading coursetransit-my-courses__heading">' . esc_html__('My Courses', 'coursetransit') . '</h2>';
    echo '<span class="coursetransit-my-courses__count">' . esc_html($course_count . ' ' . _n('course', 'courses', $course_count, 'coursetransit')) . '</span>';
    echo '</div>';
}
if ($sort === 'name-asc') {
    usort($courses, static function ($a, $b) { return strcasecmp((string) $a['fullname'], (string) $b['fullname']); });
} elseif ($sort === 'name-desc') {
    usort($courses, static function ($a, $b) { return strcasecmp((string) $b['fullname'], (string) $a['fullname']); });
} elseif ($sort === 'progress-desc' || $sort === 'progress-asc') {
    usort($courses, static function ($a, $b) use ($sort) {
        $ap = coursetransit_blocks_get_course_progress($a)['percent'];
        $bp = coursetransit_blocks_get_course_progress($b)['percent'];
        return $sort === 'progress-desc' ? ($bp <=> $ap) : ($ap <=> $bp);
    });
}
$courses = array_slice($courses, 0, $limit);

if (!$courses) {
    echo '<div class="coursetransit-block-notice"><p>' . esc_html__('You do not have any courses yet.', 'coursetransit') . '</p></div></div>';
    return;
}

echo '<div class="coursetransit-my-courses-grid" style="--ct-columns:' . esc_attr($columns) . '">';

foreach ($courses as $course) {
    $product_id = absint($course['wc_product_id']);
    $product = wc_get_product($product_id);
    if (!$product || $product->get_status() !== 'publish') continue;

    $permalink = get_permalink($product_id);
    if (!$permalink) continue;
    $course_url = coursetransit_blocks_moodle_course_url($course);
    if ($course_url !== '') { $permalink = $course_url; }

    $title = trim((string) $course['fullname']) ?: $product->get_name();
    $summary = coursetransit_blocks_get_course_short_description($course, $product);
    $summary = trim(wp_strip_all_tags($summary));
    $summary = $summary !== '' ? wp_trim_words($summary, 24, '…') : '';

    echo '<article class="coursetransit-my-course-card">';
    if ($show_image) {
        $image_sizes = $columns === 4 ? '(max-width: 600px) 100vw, (max-width: 782px) 50vw, 25vw' : ($columns === 3 ? '(max-width: 600px) 100vw, (max-width: 782px) 50vw, 33.333vw' : ($columns === 2 ? '(max-width: 600px) 100vw, 50vw' : '100vw'));
        $image = coursetransit_blocks_course_image($course, $product, $image_size, $image_sizes);
        if ($image) {
            echo '<a class="coursetransit-my-course-card-image coursetransit-my-course-card-image--' . esc_attr($image_ratio) . '" href="' . esc_url($permalink) . '">' . wp_kses($image, ['img' => ['src' => true, 'alt' => true, 'class' => true, 'width' => true, 'height' => true, 'loading' => true, 'decoding' => true, 'srcset' => true, 'sizes' => true, 'style' => true]]) . '</a>';
        }
    }
    echo '<div class="coursetransit-my-course-card-content">';
    echo '<div class="coursetransit-my-course-card-status">' . esc_html__('ENROLLED', 'coursetransit') . '</div>';
    echo '<h3 class="coursetransit-my-course-card-title"><a href="' . esc_url($permalink) . '">' . esc_html($title) . '</a></h3>';

    $meta_parts = [];
    $terms = get_the_terms($product_id, 'product_cat');
    if (!is_wp_error($terms) && !empty($terms)) {
        $meta_parts[] = implode(', ', wp_list_pluck($terms, 'name'));
    }
    $instructors = coursetransit_blocks_get_course_instructors(absint($course['id'] ?? 0));
    if ($instructors) {
        $meta_parts[] = implode(', ', $instructors);
    }
    $enrolled_at = isset($enrollment_map[$product_id]) ? (int) $enrollment_map[$product_id] : 0;
    if ($enrolled_at) {
        /* translators: %s: date the learner enrolled in the course. */
        $meta_parts[] = sprintf(__('Enrolled %s', 'coursetransit'), wp_date(get_option('date_format'), $enrolled_at));
    }
    if ($meta_parts) {
        echo '<div class="coursetransit-my-course-card-meta">' . esc_html(implode(' • ', $meta_parts)) . '</div>';
    }
    if ($show_description && $summary !== '') {
        echo '<p class="coursetransit-my-course-card-description">' . esc_html($summary) . '</p>';
    }
    if ($show_progress) {
        coursetransit_blocks_render_progress($course, get_current_user_id());
    }
    $progress_data = coursetransit_blocks_get_course_progress($course, get_current_user_id());
    $cta_text = $button_text;
    if ($button_text === __('Continue Course', 'coursetransit') || $button_text === __('Start Course', 'coursetransit')) {
        $cta_text = $progress_data['percent'] >= 100 ? __('View Course', 'coursetransit') : ($progress_data['percent'] > 0 ? __('Continue Course', 'coursetransit') : __('Start Course', 'coursetransit'));
    }
    echo '<a class="wp-block-button__link wp-element-button coursetransit-my-course-card-button" href="' . esc_url($permalink) . '">' . esc_html($cta_text) . '</a>';
    echo '</div></article>';
}
echo '</div></div>';

})();
