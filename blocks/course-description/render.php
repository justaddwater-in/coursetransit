<?php
/**
 * Dynamic renderer for the CourseTransit single-course block.
 *
 * Displays one CourseTransit course as a complete course card.
 */
defined('ABSPATH') || exit;

(static function () use ($attributes) {

if (!function_exists('wc_get_product')) {
    return;
}

require_once dirname(__DIR__) . '/helpers.php';

$product_id = isset($attributes['productId']) ? absint($attributes['productId']) : 0;
$course_id = isset($attributes['courseId']) ? absint($attributes['courseId']) : 0;

if (!$product_id && $course_id) {
    $selected_course = coursetransit_blocks_get_course_by_id($course_id);
    if ($selected_course) {
        $product_id = absint($selected_course['wc_product_id']);
    }
}

if (!$product_id && function_exists('is_product') && is_product()) {
    $product_id = get_queried_object_id();
}

if (!$product_id) {
    echo '<div class="coursetransit-block-notice"><p>' . esc_html__('Select a course in the block settings, set a Product ID, or place this block on a WooCommerce course page.', 'coursetransit') . '</p></div>';
    return;
}

$product = wc_get_product($product_id);
$course  = $product ? coursetransit_blocks_get_course_by_product_id($product_id) : null;

if (!$product || !$course || $product->get_status() !== 'publish') {
    echo '<div class="coursetransit-block-notice"><p>' . esc_html__('Course product not found or is not published.', 'coursetransit') . '</p></div>';
    return;
}

$show_image       = !isset($attributes['showImage']) || (bool) $attributes['showImage'];
$show_title       = !isset($attributes['showTitle']) || (bool) $attributes['showTitle'];
$show_description = !isset($attributes['showDescription']) || (bool) $attributes['showDescription'];
$show_price       = !isset($attributes['showPrice']) || (bool) $attributes['showPrice'];
$show_category    = !isset($attributes['showCategory']) || (bool) $attributes['showCategory'];
$show_instructor  = !isset($attributes['showInstructor']) || (bool) $attributes['showInstructor'];
$show_progress   = !isset($attributes['showProgress']) || (bool) $attributes['showProgress'];
$button_text      = isset($attributes['buttonText']) ? trim((string) $attributes['buttonText']) : '';
$button_text      = $button_text !== '' ? $button_text : __('View Course', 'coursetransit');
$image_size       = isset($attributes['imageSize']) ? sanitize_key((string) $attributes['imageSize']) : 'large';
$image_size       = in_array($image_size, ['thumbnail', 'medium', 'medium_large', 'large', 'full'], true) ? $image_size : 'large';
$image_ratio      = isset($attributes['imageRatio']) ? sanitize_key((string) $attributes['imageRatio']) : '16-9';
$image_ratio      = in_array($image_ratio, ['16-9', '4-3', '1-1', 'auto'], true) ? $image_ratio : '16-9';

$title = trim((string) ($course['fullname'] ?? ''));
if ($title === '') {
    $title = $product->get_name();
}

$description = coursetransit_blocks_get_course_full_description($course, $product);

$price_html = $show_price ? $product->get_price_html() : '';
$permalink  = get_permalink($product_id);
$image_html = $show_image ? coursetransit_blocks_course_image($course, $product, $image_size, '100vw') : '';

$category_names = [];
if ($show_category) {
    $terms = get_the_terms($product_id, 'product_cat');
    if (!is_wp_error($terms) && !empty($terms)) {
        foreach ($terms as $term) {
            $category_names[] = $term->name;
        }
    }
}

$instructor_names = $show_instructor
    ? coursetransit_blocks_get_course_instructors(absint($course['id'] ?? 0))
    : [];

$wrapper = get_block_wrapper_attributes(['class' => 'coursetransit-block coursetransit-single-course']);
// phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by get_block_wrapper_attributes(), which escapes attribute values.
echo '<article ' . $wrapper . '>';

echo '<div class="coursetransit-single-course__card">';

if ($image_html !== '') {
    $ratio_class = 'coursetransit-single-course__image--' . $image_ratio;
    echo '<figure class="coursetransit-single-course__image ' . esc_attr($ratio_class) . '">';
    if ($permalink) {
        // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Image markup is generated by the WordPress image helper.
        echo '<a href="' . esc_url($permalink) . '" aria-label="' . esc_attr($title) . '">' . $image_html . '</a>';
    } else {
        // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Image markup is generated by the WordPress image helper.
        echo $image_html;
    }
    echo '</figure>';
}

echo '<div class="coursetransit-single-course__content">';

if ($show_title) {
    echo '<h2 class="wp-block-heading coursetransit-single-course__title">' . esc_html($title) . '</h2>';
}

if ($category_names || $instructor_names) {
    echo '<div class="coursetransit-single-course__meta">';
    if ($category_names) {
        echo '<span class="coursetransit-single-course__meta-item"><strong>' . esc_html__('Category:', 'coursetransit') . '</strong> ' . esc_html(implode(', ', $category_names)) . '</span>';
    }
    if ($instructor_names) {
        echo '<span class="coursetransit-single-course__meta-item"><strong>' . esc_html__('Instructor:', 'coursetransit') . '</strong> ' . esc_html(implode(', ', $instructor_names)) . '</span>';
    }
    echo '</div>';
}

if ($show_price && $price_html !== '') {
    echo '<div class="coursetransit-single-course__price">' . wp_kses_post($price_html) . '</div>';
}

if ($show_progress && is_user_logged_in()) {
    $enrolled_ids = coursetransit_blocks_get_enrolled_product_ids(get_current_user_id());
    if (in_array($product_id, $enrolled_ids, true)) {
        coursetransit_blocks_render_progress($course, get_current_user_id());
    }
}

if ($show_description && $description !== '') {
    echo '<div class="coursetransit-single-course__description">' . wp_kses_post($description) . '</div>';
}

if ($permalink) {
    echo '<div class="wp-block-buttons coursetransit-single-course__actions">';
    echo '<div class="wp-block-button"><a class="wp-block-button__link wp-element-button" href="' . esc_url($permalink) . '">' . esc_html($button_text) . '</a></div>';
    echo '</div>';
}

echo '</div></div></article>';

})();
